// Portable source bundle for GitHub Pages deployed from docs/. No runtime dependencies.
import { readFile, writeFile } from 'node:fs/promises';
const files = ['constants', 'rpc', 'payments', 'keccak', 'base-scanner', 'solana-scanner'];
export async function browserSource() {
  return '// Generated by node scripts/build-browser.mjs; edit src/ instead.\n' + (await Promise.all(files.map(async name => `\n// src/${name}.js\n` + (await readFile(new URL(`../src/${name}.js`, import.meta.url), 'utf8')).replace(/^import .*;\n/gm, '')))).join('\n');
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) await writeFile(new URL('../docs/scanner-core.js', import.meta.url), await browserSource());
